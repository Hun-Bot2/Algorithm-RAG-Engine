import {identifier,timestamp} from './core/events.mjs';

const escapeSlack = value => String(value ?? '').replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;');
const bounded = (value,n) => String(value ?? '').slice(0,n);
const hex = bytes => [...new Uint8Array(bytes)].map(b=>b.toString(16).padStart(2,'0')).join('');
async function sha256(value) { return hex(await crypto.subtle.digest('SHA-256',new TextEncoder().encode(value))); }
const canonicalJson = value => JSON.stringify(value,(_,v)=>v && typeof v==='object' && !Array.isArray(v) ? Object.fromEntries(Object.entries(v).sort(([a],[b])=>a.localeCompare(b))) : v);

export async function deliveryKey(learnerId,localDate,channelId) {
  identifier(learnerId); identifier(channelId);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(localDate)) throw new Error('invalid local date');
  return `ARE:v1:${localDate}:${(await sha256(learnerId+'\0'+localDate+'\0'+channelId)).slice(0,20)}`;
}

const allowedHosts={leetcode:'leetcode.com',atcoder:'atcoder.jp',codeforces:'codeforces.com',baekjoon:'www.acmicpc.net'};
function canonicalLink(problem) {
  if (problem?.review?.status!=='approved' || problem?.access_state!=='free') return null;
  try {
    const url=new URL(problem.canonical_url),platform=problem.problem_key.split(':')[0];
    if (url.protocol!=='https:' || url.hostname!==allowedHosts[platform] || url.username || url.password || url.port || url.search || url.hash || !url.pathname) return null;
    return url.href;
  } catch { return null; }
}

export function formatMissionSlack(mission,curriculum,annotations={},marker) {
  if (!mission || !/^\d{4}-\d{2}-\d{2}$/.test(mission.date) || !Array.isArray(mission.activities) || typeof marker!=='string') throw new Error('invalid mission message');
  const lookup=new Map((curriculum.problems ?? []).map(problem=>[problem.problem_key,problem]));
  const title=`Daily Algorithm Review (${mission.date})`;
  const blocks=[
    {type:'header',text:{type:'plain_text',text:title}},
    {type:'section',text:{type:'mrkdwn',text:`오늘의 활동 *${Math.min(mission.activities.length,10)}개*`}},
    {type:'divider'},
  ];
  const lines=[title];
  for (const activity of mission.activities.slice(0,10)) {
    const problem=lookup.get(activity.problem_key),label=bounded(annotations?.[activity.problem_key]?.title ?? activity.title ?? activity.problem_key ?? activity.contest_id ?? '활동',160);
    const link=canonicalLink(problem);
    const display=link ? `<${link}|${escapeSlack(label)}>` : escapeSlack(label);
    const type=activity.type==='review'?'복습':activity.type==='contest'?'대회':activity.type==='upsolve'?'업솔브':activity.type==='virtual'?'버추얼':activity.type==='transfer'?'응용':'연습';
    const reason=bounded(escapeSlack(activity.reason ?? ''),1200);
    const detail=`*${type}* ${display}${reason?'\n'+reason:''}`;
    blocks.push({type:'section',text:{type:'mrkdwn',text:bounded(detail,3000)}});
    blocks.push({type:'divider'});
    lines.push(`${type}: ${label}`);
  }
  blocks.push({type:'context',elements:[{type:'mrkdwn',text:`Generated by Algorithm RAG Engine · ${escapeSlack(marker)}`}]});
  const text=bounded(lines.join(' · ')+' · '+marker,3000);
  if (blocks.length>50 || blocks.some(block=>block.text?.text?.length>3000)) throw new Error('Slack block limit exceeded');
  return {text,blocks};
}

export function formatLegacyRecommendationBlock(problem) {
  const id=problem?.id ?? 'Unknown ID',title=problem?.title ?? 'Unknown Title';
  const tags=(problem?.tags ?? []).slice(0,3).map(tag=>`\`${tag}\``).join(', ') || 'No tags';
  const recommendations=(problem?.recommendations ?? []).slice(0,3).map(rec=>{
    const name=rec.title ?? 'Unknown',slug=String(name).toLowerCase().trim().replace(/ /g,'-').replace(/[^a-z0-9-]/g,'');
    const url=slug?`https://leetcode.com/problems/${slug}/`:'https://leetcode.com/problemset/all/';
    return `• <${url}|${name}> (Sim: ${rec.similarity ?? 0})${rec.ai_comment?'\n  > '+rec.ai_comment:''}`;
  }).join('\n') || '• No recommendations available';
  return {type:'section',text:{type:'mrkdwn',text:`*[${id}] ${title}*\nTags: ${tags}\n*Similar LeetCode Problems:*\n${recommendations}`}};
}

const resultCount = result => result?.meta?.changes ?? result?.changes ?? 0;
export async function ensureDelivery(db,{learnerId,mission,curriculum,annotations={},channelId,now}) {
  const localDate=mission.date, key=await deliveryKey(learnerId,localDate,channelId);
  const missionJson=canonicalJson(mission), missionHash=await sha256(missionJson);
  const messageJson=canonicalJson(formatMissionSlack(mission,curriculum,annotations,key));
  const at=timestamp(now.toISOString());
  await db.prepare(`INSERT OR IGNORE INTO delivery_outbox
    (learner_id,local_date,channel_id,uniqueness_key,mission_hash,mission_payload,message_payload,state,created_at,updated_at)
    VALUES (?,?,?,?,?,?,?,'ready',?,?)`).bind(learnerId,localDate,channelId,key,missionHash,missionJson,messageJson,at,at).run();
  const row=await db.prepare('SELECT * FROM delivery_outbox WHERE learner_id=? AND local_date=? AND channel_id=?').bind(learnerId,localDate,channelId).first();
  if (!row || row.mission_hash!==missionHash || row.uniqueness_key!==key) throw new Error('delivery snapshot conflict');
  return row;
}
export async function listDeliveries(db,learnerId) {
  identifier(learnerId);
  const rows=(await db.prepare('SELECT local_date,channel_id,state,retry_at,scheduled_message_id,slack_ts,last_error_code,created_at,updated_at FROM delivery_outbox WHERE learner_id=? ORDER BY local_date DESC, channel_id LIMIT 30').bind(learnerId).all()).results;
  return rows;
}
export async function claimDelivery(db,{learnerId,localDate,channelId,now,deadline,leaseSeconds=90}) {
  const at=timestamp(now.toISOString()), until=timestamp(new Date(now.getTime()+leaseSeconds*1000).toISOString());
  if (now>deadline) return null;
  const result=await db.prepare(`UPDATE delivery_outbox SET state='sending',lease_until=?,retry_at=NULL,attempt_count=attempt_count+1,updated_at=?
    WHERE learner_id=? AND local_date=? AND channel_id=? AND state='ready' AND (retry_at IS NULL OR retry_at<=?)`).bind(until,at,learnerId,localDate,channelId,at).run();
  if (resultCount(result)!==1) return null;
  return db.prepare('SELECT * FROM delivery_outbox WHERE learner_id=? AND local_date=? AND channel_id=?').bind(learnerId,localDate,channelId).first();
}
export async function transitionDelivery(db,{key,from,to,now,retryAt=null,scheduledId=null,slackTs=null,errorCode=null}) {
  const result=await db.prepare(`UPDATE delivery_outbox SET state=?,retry_at=?,lease_until=NULL,scheduled_message_id=COALESCE(?,scheduled_message_id),slack_ts=COALESCE(?,slack_ts),last_error_code=?,updated_at=? WHERE uniqueness_key=? AND state=?`).bind(to,retryAt,scheduledId,slackTs,errorCode,timestamp(now.toISOString()),key,from).run();
  return resultCount(result)===1;
}
export async function expireSending(db,learnerId,now) {
  const result=await db.prepare(`UPDATE delivery_outbox SET state='unknown',lease_until=NULL,last_error_code='send_lease_expired',updated_at=? WHERE learner_id=? AND state='sending' AND lease_until<=?`).bind(timestamp(now.toISOString()),learnerId,timestamp(now.toISOString())).run();
  return resultCount(result);
}
export async function missReady(db,{learnerId,localDate,channelId,now,reason}) {
  const result=await db.prepare(`UPDATE delivery_outbox SET state='missed',last_error_code=?,retry_at=NULL,updated_at=? WHERE learner_id=? AND local_date=? AND channel_id=? AND state='ready'`).bind(reason,timestamp(now.toISOString()),learnerId,localDate,channelId).run();
  return resultCount(result)===1;
}
export async function listUnresolved(db,learnerId) {
  return (await db.prepare("SELECT * FROM delivery_outbox WHERE learner_id=? AND state IN ('unknown','scheduled') ORDER BY local_date DESC LIMIT 30").bind(learnerId).all()).results;
}
