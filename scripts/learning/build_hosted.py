"""Generate a bounded reviewed curriculum module; never copy legacy/index/research assets."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from src.learning.curriculum import validate_curriculum


def build(*, draft=False):
    seed_path = ROOT / 'curriculum/seed.v1.json'
    annotations_path = ROOT / 'curriculum/annotations.v1.json'
    if not draft:
        registry=json.loads((ROOT/'assets/curriculum_release.v1.json').read_text())
        expected={'curriculum/seed.v1.json','curriculum/annotations.v1.json'}
        if registry.get('schema_version')!=1 or set(registry.get('files',{}))!=expected:
            raise ValueError('curated release registry is incomplete')
        for relative,digest in registry['files'].items():
            if hashlib.sha256((ROOT/relative).read_bytes()).hexdigest()!=digest:
                raise ValueError('curated release asset drift; review a new asset version')
    seed = json.loads(seed_path.read_text())
    validate_curriculum(seed, require_release=not draft)
    annotations_doc = json.loads(annotations_path.read_text())
    annotations = annotations_doc.get('annotations', annotations_doc)
    if isinstance(annotations, list):
        annotations = {a['problem_key']: a for a in annotations}
    keys = {p['problem_key'] for p in seed['problems']}
    if set(annotations) != keys:
        raise ValueError('annotation keys do not match the curriculum')
    output = ROOT / 'hosted/generated/curriculum.mjs'
    output.parent.mkdir(parents=True, exist_ok=True)
    manifest = {name: hashlib.sha256(path.read_bytes()).hexdigest() for name,path in
                [('seed_sha256',seed_path),('annotations_sha256',annotations_path)]}
    manifest.update(schema_version=1, draft=draft, included_paths=['curriculum/seed.v1.json','curriculum/annotations.v1.json'],
                    excluded='All historical data/indexes, learner state, secrets and research judgments')
    output.write_text('// Generated by scripts/learning/build_hosted.py; no model assets.\n' +
                      'export const curriculum = ' + json.dumps(seed,ensure_ascii=False) + ';\n' +
                      'export const annotations = ' + json.dumps(annotations,ensure_ascii=False) + ';\n' +
                      'export const manifest = ' + json.dumps(manifest) + ';\n')
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--draft',action='store_true',help='Local preview only; does not approve any record')
    args = parser.parse_args()
    try:
        print(json.dumps(build(draft=args.draft),indent=2))
    except (ValueError,KeyError,OSError) as exc:
        sys.exit(str(exc))
